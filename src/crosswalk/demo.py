"""``crosswalk demo``: the whole streaming pipeline in one process.

No Kafka, no S3, no GPU: the same stage code as the cluster, wired to the
in-memory bus (:class:`~crosswalk.stream.bus.MemoryBus`) and a local
directory instead of a bucket::

    sampler -> frames.v1 -> inference -> detections.v1 -> tracking -> tracks.v1
            -> indicators -> indicators.v1 -> ranking -> leaderboard.json / page

Frame sources, in order of fidelity:

- default: the generated crossing scene (:mod:`crosswalk.scene`), sampled
  in Python and written as JPEGs, like the Rust sampler does;
- ``--video``: the scene encoded as a real clip and decoded with PyAV;
- ``--ingest-bin``: the clip decoded and sampled by the Rust
  ``crosswalk-ingest`` binary in its local mode, then replayed onto the bus.

The detector is :class:`~crosswalk.scene.SceneDetector` (finds the drawn
shapes by colour), because the pretrained FCOS model sees nothing in
coloured rectangles. Everything after detection is production code.

Stages run one after another until each input topic is drained. The topics
buffer between them exactly as Kafka would, and running sequentially keeps
the output deterministic for the integration test.
"""

from __future__ import annotations

import io
import json
import logging
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from crosswalk import scene
from crosswalk.config import BatchingConfig, InferenceConfig, StreamConfig, TrackingStageConfig
from crosswalk.indicators.camera import Calibration, CameraConfig
from crosswalk.stream import events as ev
from crosswalk.stream.bus import MemoryBus, TopicSpec

log = logging.getLogger(__name__)

DEMO_SCENES = [
    scene.SceneConfig(name="synthetic-demo", seed=1, yielding=True),
    scene.SceneConfig(name="synthetic-demo-impatient", seed=2, yielding=False, vehicles_per_min=18),
]


def camera_config(name: str, crossing: str) -> CameraConfig:
    """The generated scene is a plan view at 20 px/m: exact calibration."""
    w_m, h_m = scene.WIDTH / scene.PX_PER_M, scene.HEIGHT / scene.PX_PER_M
    return CameraConfig(
        camera_id=name,
        crossing=crossing,
        location="Generated test scene (not a real place)",
        frame_size=(scene.WIDTH, scene.HEIGHT),
        calibration=Calibration(
            image_points=[(0, 0), (scene.WIDTH, 0), (scene.WIDTH, scene.HEIGHT), (0, scene.HEIGHT)],
            world_points=[(0, 0), (w_m, 0), (w_m, h_m), (0, h_m)],
            reference="generated scene drawn at 20 px per metre",
        ),
        source="generated by crosswalk demo",
        license="not applicable (synthetic)",
    )


@dataclass
class DemoResult:
    out_dir: Path
    counts: dict[str, dict[str, int]]
    topics: dict[str, int]
    leaderboard: dict[str, Any]
    seconds: float


def _jpeg(image) -> bytes:
    from PIL import Image

    buf = io.BytesIO()
    Image.fromarray(image).save(buf, format="JPEG", quality=92)
    return buf.getvalue()


def _publish_scene(
    bus: MemoryBus, cfg: scene.SceneConfig, frames_dir: Path, fps: float, run_id: str
) -> int:
    """Python stand-in for the Rust sampler: JPEG to local storage, then a
    frame event pointing at it; an end event when the clip is done."""
    import hashlib

    producer = bus.producer()
    stream_id = f"{cfg.name}/{cfg.name}/{run_id}-0"
    keep_every = max(1, round(cfg.fps / fps))
    published = 0
    last_pts = 0.0
    for frame in scene.frames(cfg):
        last_pts = frame.pts_s
        if frame.index % keep_every:
            continue
        key = f"frames/{cfg.name}/{cfg.name}/{frame.index:08d}.jpg"
        data = _jpeg(frame.image)
        path = frames_dir / key
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        event = ev.FrameEvent(
            frame_id=f"{stream_id}/{frame.index}", stream_id=stream_id, camera_id=cfg.name,
            clip=f"{cfg.name}.mp4", frame_index=frame.index, sample_index=published, pts_s=frame.pts_s,
            width=scene.WIDTH, height=scene.HEIGHT, decoded_at=time.time(), published_at=time.time(),
            image=ev.ObjectRef(bucket="local", key=key), bytes=len(data),
            sha256=hashlib.sha256(data).hexdigest(),
        )  # fmt: skip
        producer.send(ev.TOPIC_FRAMES, cfg.name, event.to_bytes())
        published += 1
    end = ev.EndEvent(
        stream_id=stream_id,
        camera_id=cfg.name,
        clip=f"{cfg.name}.mp4",
        frames=published,
        last_pts_s=last_pts,
    )
    producer.send(ev.TOPIC_FRAMES, cfg.name, end.to_bytes())
    return published


def _publish_video(bus: MemoryBus, clip: Path, frames_dir: Path, fps: float, run_id: str) -> int:
    """Decode a real clip with PyAV and sample it by timestamp."""
    import hashlib

    from crosswalk.inference import video

    producer = bus.producer()
    camera = ev.camera_id_from_clip(clip.name)
    stream_id = f"{camera}/{clip.stem}/{run_id}-0"
    next_due = 0.0
    published = 0
    last_pts = 0.0
    for frame in video.iter_frames(str(clip)):
        last_pts = frame.pts_s
        if frame.pts_s + 1e-6 < next_due:
            continue
        next_due = frame.pts_s + 1.0 / fps
        key = f"frames/{camera}/{clip.stem}/{frame.index:08d}.jpg"
        data = _jpeg(frame.image)
        (frames_dir / key).parent.mkdir(parents=True, exist_ok=True)
        (frames_dir / key).write_bytes(data)
        event = ev.FrameEvent(
            frame_id=f"{stream_id}/{frame.index}", stream_id=stream_id, camera_id=camera, clip=clip.name,
            frame_index=frame.index, sample_index=published, pts_s=frame.pts_s, width=frame.width,
            height=frame.height, decoded_at=time.time(), image=ev.ObjectRef(bucket="local", key=key),
            bytes=len(data), sha256=hashlib.sha256(data).hexdigest(),
        )  # fmt: skip
        producer.send(ev.TOPIC_FRAMES, camera, event.to_bytes())
        published += 1
    end = ev.EndEvent(
        stream_id=stream_id, camera_id=camera, clip=clip.name, frames=published, last_pts_s=last_pts
    )
    producer.send(ev.TOPIC_FRAMES, camera, end.to_bytes())
    return published


def _publish_with_rust(bus: MemoryBus, binary: str, clip: Path, out: Path, fps: float) -> int:
    """Run the Rust sampler in local mode and replay its events onto the bus."""
    ingest_dir = out / "ingest"
    events_file = ingest_dir / "events.jsonl"
    # The sampler appends; replay only what this run added.
    already = len(events_file.read_text().splitlines()) if events_file.exists() else 0
    subprocess.run(
        [
            binary,
            str(clip),
            "--sampling",
            f"fps:{fps}",
            "--local-dir",
            str(ingest_dir),
            "--listen",
            "127.0.0.1:0",
        ],
        check=True,
    )
    producer = bus.producer()
    n = 0
    for line in events_file.read_text().splitlines()[already:]:
        record = json.loads(line)
        key = record.pop("_key")
        # In local mode the sampler's "bucket" is its output directory, which
        # the demo's fetcher resolves like a bucket name.
        n += record.get("type") == "frame"
        producer.send(ev.TOPIC_FRAMES, key, json.dumps(record).encode())
    return n


def run(
    out_dir: str | Path,
    *,
    seconds: float = 120.0,
    fps: float = 5.0,
    window_s: float = 15.0,
    video: bool = False,
    ingest_bin: str | None = None,
) -> DemoResult:
    from crosswalk.indicators.stage import IndicatorsHandler
    from crosswalk.inference import stream_mode
    from crosswalk.inference.metrics import Metrics
    from crosswalk.inference.stream_mode import FrameFetcher
    from crosswalk.ranking import leaderboard
    from crosswalk.ranking.service import RankingStageConfig
    from crosswalk.ranking.service import build_runner as ranking_runner
    from crosswalk.ranking.store import Store
    from crosswalk.stream.stage import RunnerConfig, StageRunner
    from crosswalk.tracking.stage import build_runner as tracking_runner

    started = time.monotonic()
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    frames_root = out / "frames-root"
    frames_root.mkdir(exist_ok=True)
    bus = MemoryBus()
    bus.ensure_topics([TopicSpec(ev.TOPIC_FRAMES, 3)])
    run_id = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())

    scenes = [scene.SceneConfig(**{**s.__dict__, "seconds": seconds}) for s in DEMO_SCENES]
    cameras = {
        "synthetic-demo": camera_config("synthetic-demo", "Generated crossing, drivers yield"),
        "synthetic-demo-impatient": camera_config(
            "synthetic-demo-impatient", "Generated crossing, drivers do not yield"
        ),
    }
    # 1. Sample frames into local storage and the frames topic.
    for cfg in scenes:
        if video or ingest_bin:
            clip = out / "clips" / f"{cfg.name}.mp4"
            clip.parent.mkdir(exist_ok=True)
            scene.write_video(str(clip), cfg, encoder="ffmpeg" if ingest_bin else "av")
            if ingest_bin:
                _publish_with_rust(bus, ingest_bin, clip, out, fps)
            else:
                _publish_video(bus, clip, frames_root, fps, run_id)
        else:
            _publish_scene(bus, cfg, frames_root, fps, run_id)

    # 2. Inference (dynamic batching through the real batcher and worker).
    def local_get(ref: ev.ObjectRef) -> bytes | None:
        root = frames_root if ref.bucket == "local" else Path(ref.bucket)
        path = root / ref.key
        return path.read_bytes() if path.exists() else None

    metrics = Metrics()
    inference_cfg = InferenceConfig(
        mode="kafka",
        batching=BatchingConfig(strategy="dynamic", max_batch_size=8, max_wait_ms=5),
        kafka={"poll_timeout_s": 0.05},
    )
    runner, worker, handler, batcher = stream_mode.build(
        inference_cfg, bus, scene.SceneDetector(), metrics, fetch=FrameFetcher(local_get)
    )
    counts: dict[str, dict[str, int]] = {}
    runner.start()
    worker.start()
    try:
        counts["inference"] = runner.run(until_idle=True)
    finally:
        batcher.close()
        worker.join(10)
        handler.close()

    # 3. Tracking.
    fast = StreamConfig(poll_timeout_s=0.05, max_records=256)
    tracking = tracking_runner(
        TrackingStageConfig(kafka=fast.model_copy(update={"group": "crosswalk-tracking"})), bus
    )
    counts["tracking"] = tracking.run(until_idle=True)

    # 4. Indicators (cameras from code: exact calibration of the generated scene).
    indicators = StageRunner(
        IndicatorsHandler(dict(cameras), window_s=window_s),
        bus,
        RunnerConfig(
            group="crosswalk-indicators",
            input_topics=[ev.TOPIC_TRACKS],
            topics=[TopicSpec(ev.TOPIC_TRACKS, 3), TopicSpec(ev.TOPIC_INDICATORS, 3)],
            poll_timeout_s=0.05,
            max_records=256,
        ),
    )
    counts["indicators"] = indicators.run(until_idle=True)

    # 5. Ranking: store windows, build the leaderboard with demo-sized rules.
    ranking_cfg = RankingStageConfig(
        kafka=fast.model_copy(update={"group": "crosswalk-ranking"}),
        database=str(out / "ranking.sqlite3"),
        min_observed_s=min(60.0, seconds / 2),
        min_windows=2,
        # Demo-sized rules: a couple of minutes of generated video per
        # crossing would never meet the production minimums.
        min_pedestrian_minutes=0.1,
    )
    store = Store(ranking_cfg.database)
    counts["ranking"] = ranking_runner(ranking_cfg, bus, store).run(until_idle=True)
    board = leaderboard.build(store.windows(), cameras, ranking_cfg.rules())
    board["demo"] = True
    store.save_snapshot(board)
    store.close()

    (out / "leaderboard.json").write_text(json.dumps(board, indent=2, default=str))
    from importlib import resources

    page = resources.files("crosswalk.ranking").joinpath("leaderboard.html").read_text()
    # A static copy that reads the JSON next to it (open it via `crosswalk demo --serve`
    # or any static file server; browsers block fetch() from file:// URLs).
    (out / "index.html").write_text(page)
    (out / "api").mkdir(exist_ok=True)
    (out / "api" / "leaderboard").write_text(json.dumps(board, default=str))
    (out / "api" / "history").write_text(json.dumps({"snapshots": []}))
    topics = {t: len(bus.messages(t)) for t in bus.topics()}
    (out / "metrics.prom").write_bytes(metrics.render())
    return DemoResult(out, counts, topics, board, time.monotonic() - started)


def serve(out_dir: str | Path, port: int) -> None:
    """Serve the demo's output directory (the page and its JSON)."""
    import functools
    import http.server

    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(out_dir))
    with http.server.ThreadingHTTPServer(("127.0.0.1", port), handler) as httpd:
        print(f"leaderboard at http://127.0.0.1:{httpd.server_address[1]}/ (Ctrl-C to stop)")
        httpd.serve_forever()
